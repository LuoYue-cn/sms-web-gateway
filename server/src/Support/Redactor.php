<?php
declare(strict_types=1);

namespace SmsGate\Support;

/**
 * 发给外部 AI 之前对短信正文做脱敏。宁可多替换：验证码、手机号、卡号、金额、证件号、链接、
 * 邮箱、取件码以及所有 5 位以上的数字串都会换成方括号占位符。
 * 姓名、地址这类自然语言信息无法可靠识别，所以界面上提供「预览将发送的内容」。
 */
final class Redactor
{
    public static function redact(string $text, ?string $code = null): string
    {
        if ($code !== null && $code !== '') {
            $text = str_replace($code, '[验证码]', $text);
            if (preg_match('/^[0-9]{6}$/', $code) === 1) {
                $text = (string) preg_replace('/' . substr($code, 0, 3) . '[ \-]' . substr($code, 3) . '/', '[验证码]', $text);
            }
        }
        $rules = [
            ['~https?://\S+|www\.\S+~iu', '[链接]'],
            ['/[A-Za-z0-9._%+\-]+@[A-Za-z0-9.\-]+\.[A-Za-z]{2,}/', '[邮箱]'],
            ['/(?<![0-9A-Za-z])[0-9]{17}[0-9Xx](?![0-9A-Za-z])/', '[证件号]'],
            ['/(取件码|取货码|提货码|收货码|提取码)\s*[:：]?\s*[A-Za-z0-9\-]{3,12}/u', '$1[取件码]'],
            ['/(?<![0-9])(?:\+?86[ \-]?)?1[3-9][0-9][ \-]?[0-9]{4}[ \-]?[0-9]{4}(?![0-9])/', '[手机号]'],
            ['/(?<![0-9A-Za-z])\+[0-9]{1,3}[ \-]?[0-9]{6,14}(?![0-9])/', '[手机号]'],
            ['/[¥￥$＄€£]\s*[0-9][0-9,]*(?:\.[0-9]+)?/u', '[金额]'],
            ['/[0-9][0-9,]*(?:\.[0-9]+)?\s*(?:万元|元|块钱|块|美元|港币|人民币|RMB|USD|CNY)/iu', '[金额]'],
            ['/(尾号|卡号|末四位|后四位)\s*[为是:：]?\s*[0-9]{3,4}/u', '$1[尾号]'],
            ['/(?<![0-9])[0-9]{5,}(?![0-9])/', '[数字]'],
            ['/(?<![A-Za-z0-9])(?=[A-Za-z0-9]*[0-9])(?=[A-Za-z0-9]*[A-Za-z])[A-Za-z0-9]{8,}(?![A-Za-z0-9])/', '[编号]'],
        ];
        foreach ($rules as [$re, $to]) {
            $text = (string) preg_replace($re, $to, $text);
        }
        return trim((string) preg_replace('/\s+/u', ' ', $text));
    }
}
